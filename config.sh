#!/bin/bash
# shellcheck disable=SC2034  # variables are used by the scripts that source this file
# Shared settings for all scripts in this repository.
# Edit the values here; every other script sources this file.

# DOMjudge version. The domserver and every judgehost MUST use the same version.
# See https://hub.docker.com/r/domjudge/domserver/tags
DOMJUDGE_VERSION=9.0.1

# MariaDB version. Pinned on purpose: "latest" can change under you between
# the test round and the real contest.
MARIADB_VERSION=11.8

# Timezone used inside the containers (contest times are shown in this zone).
TIMEZONE=Asia/Tehran

# Database passwords. Change these before the real contest.
MYSQL_PASSWORD=mysql_password
MYSQL_ROOT_PASSWORD=mysql_root_password

# Port on the host where the DOMjudge web interface is published.
DOMSERVER_PORT=12345

# --- Judgehost (worker) settings -------------------------------------------

# URL of the DOMjudge server as seen from the judgehost.
# - Leave empty when the judgehost runs on the SAME machine as the domserver;
#   start_worker.sh then talks to it over the internal Docker network.
# - On a separate judge machine, set it to the server's LAN address, e.g.
#   DOMSERVER_URL=http://192.168.1.10:12345/
DOMSERVER_URL=

# Password of the "judgehost" user on the domserver. This is NOT arbitrary:
# it is generated by the domserver and printed by start_server.sh.
# - Leave empty on the server machine; start_worker.sh reads it automatically.
# - On a separate judge machine, paste the value printed by start_server.sh.
